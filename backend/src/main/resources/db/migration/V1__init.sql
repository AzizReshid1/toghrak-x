-- Initial schema for Toghrak X.
-- Mirrors the JPA entities in com.toghrakx.backend.model; Hibernate runs with ddl-auto=validate,
-- so every schema change from here on must be a new migration (V2__..., V3__..., ...).

CREATE TABLE roles (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    CONSTRAINT uk_roles_name UNIQUE (name)
);

CREATE TABLE users (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   VARCHAR(255) NOT NULL,
    email      VARCHAR(255) NOT NULL,
    password   VARCHAR(255) NOT NULL,
    role_id    BIGINT       NOT NULL,
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT fk_users_role FOREIGN KEY (role_id) REFERENCES roles (id)
);
CREATE INDEX idx_users_role_id ON users (role_id);

CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    slug        VARCHAR(150),
    description VARCHAR(255),
    CONSTRAINT uk_categories_name UNIQUE (name),
    CONSTRAINT uk_categories_slug UNIQUE (slug)
);

CREATE TABLE posts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(200) NOT NULL,
    slug        VARCHAR(255) NOT NULL,
    content     TEXT         NOT NULL,
    cover_image VARCHAR(255),
    user_id     BIGINT       NOT NULL,
    category_id BIGINT       NOT NULL,
    created_at  TIMESTAMP(6),
    updated_at  TIMESTAMP(6),
    view_count  BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_posts_slug UNIQUE (slug),
    CONSTRAINT fk_posts_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_posts_category FOREIGN KEY (category_id) REFERENCES categories (id)
);
CREATE INDEX idx_posts_category_id ON posts (category_id);
CREATE INDEX idx_posts_user_id ON posts (user_id);
CREATE INDEX idx_posts_view_count ON posts (view_count);
CREATE INDEX idx_posts_created_at ON posts (created_at);

CREATE TABLE post_images (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image_url VARCHAR(255) NOT NULL,
    post_id   BIGINT       NOT NULL,
    CONSTRAINT fk_post_images_post FOREIGN KEY (post_id) REFERENCES posts (id)
);
CREATE INDEX idx_post_images_post_id ON post_images (post_id);

CREATE TABLE pages (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug       VARCHAR(100) NOT NULL,
    title      VARCHAR(200) NOT NULL,
    content    TEXT         NOT NULL,
    updated_at TIMESTAMP(6),
    CONSTRAINT uk_pages_slug UNIQUE (slug)
);
CREATE INDEX idx_pages_updated_at ON pages (updated_at);

CREATE TABLE page_images (
    page_id   BIGINT NOT NULL,
    image_url VARCHAR(255),
    CONSTRAINT fk_page_images_page FOREIGN KEY (page_id) REFERENCES pages (id)
);
CREATE INDEX idx_page_images_page_id ON page_images (page_id);

CREATE TABLE refresh_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token      VARCHAR(255) NOT NULL,
    user_id    BIGINT       NOT NULL,
    expires_at TIMESTAMP(6) NOT NULL,
    revoked    BOOLEAN      NOT NULL,
    CONSTRAINT uk_refresh_tokens_token UNIQUE (token),
    CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX idx_refresh_tokens_user_id ON refresh_tokens (user_id);
CREATE INDEX idx_refresh_tokens_expires_at ON refresh_tokens (expires_at);
CREATE INDEX idx_refresh_tokens_revoked ON refresh_tokens (revoked);

CREATE TABLE site_settings (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title    VARCHAR(120),
    logo_url VARCHAR(2048),
    slogan   VARCHAR(200)
);

CREATE TABLE social_links (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label VARCHAR(255) NOT NULL,
    url   VARCHAR(255) NOT NULL,
    icon  VARCHAR(255)
);
